CREATE TABLE IF NOT EXISTS `maritime_course` (
    `id` bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY COMMENT '课程ID',
    `name` varchar(100) NOT NULL COMMENT '课程名称',
    `certificate_type` varchar(50) NOT NULL COMMENT '证书类型',
